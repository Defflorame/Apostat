namespace Game.Stats
{
    /// <summary>
    /// Базовые характеристики персонажа, к которым может применяться
    /// StatModifier. Производные величины (регенерация стамины, итоговый
    /// объём маны, значение защиты) сюда не входят — они всегда
    /// пересчитываются CharacterStats из этих базовых значений.
    ///
    /// ВАЖНО: порядок значений сериализуется в ассетах как число — новые
    /// характеристики добавлять ТОЛЬКО в конец.
    /// </summary>
    public enum StatType
    {
        Strength,
        Stamina,
        Mana,
        MagicDamage,
        Speed,
        CarryWeight,
        Defense,

        /// <summary>
        /// Дополнительный бонус к физическому урону в процентах (поверх бонуса от силы).
        /// Применяйте с типом Flat: значение 25 = +25% урона.
        /// </summary>
        PhysicalDamageBonus
    }
}
